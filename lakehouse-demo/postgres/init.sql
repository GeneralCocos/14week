CREATE DATABASE demo_db;
\c demo_db;

DROP TABLE IF EXISTS wide_table;

CREATE TABLE wide_table (
    id              BIGSERIAL PRIMARY KEY,
    col_01_int      INTEGER,
    col_02_int      INTEGER,
    col_03_int      INTEGER,
    col_04_int      INTEGER,
    col_05_int      INTEGER,
    col_06_num      NUMERIC(18,4),
    col_07_num      NUMERIC(18,4),
    col_08_num      NUMERIC(18,4),
    col_09_num      NUMERIC(18,4),
    col_10_num      NUMERIC(18,4),
    col_11_text     TEXT,
    col_12_text     TEXT,
    col_13_text     TEXT,
    col_14_text     TEXT,
    col_15_text     TEXT,
    col_16_bool     BOOLEAN,
    col_17_bool     BOOLEAN,
    col_18_bool     BOOLEAN,
    col_19_bool     BOOLEAN,
    col_20_bool     BOOLEAN,
    col_21_date     DATE,
    col_22_date     DATE,
    col_23_date     DATE,
    col_24_date     DATE,
    col_25_date     DATE,
    col_26_ts       TIMESTAMP,
    col_27_ts       TIMESTAMP,
    col_28_ts       TIMESTAMP,
    col_29_ts       TIMESTAMP,
    col_30_ts       TIMESTAMP,
    col_31_vc       VARCHAR(50),
    col_32_vc       VARCHAR(50),
    col_33_vc       VARCHAR(50),
    col_34_vc       VARCHAR(50),
    col_35_vc       VARCHAR(50),
    col_36_int      INTEGER,
    col_37_int      INTEGER,
    col_38_int      INTEGER,
    col_39_int      INTEGER,
    col_40_int      INTEGER,
    col_41_num      NUMERIC(10,2),
    col_42_num      NUMERIC(10,2),
    col_43_num      NUMERIC(10,2),
    col_44_num      NUMERIC(10,2),
    col_45_num      NUMERIC(10,2),
    col_46_text     TEXT,
    col_47_text     TEXT,
    col_48_text     TEXT,
    col_49_text     TEXT,
    col_50_text     TEXT
);

INSERT INTO wide_table (
  col_01_int, col_02_int, col_03_int, col_04_int, col_05_int,
  col_06_num, col_07_num, col_08_num, col_09_num, col_10_num,
  col_11_text, col_12_text, col_13_text, col_14_text, col_15_text,
  col_16_bool, col_17_bool, col_18_bool, col_19_bool, col_20_bool,
  col_21_date, col_22_date, col_23_date, col_24_date, col_25_date,
  col_26_ts, col_27_ts, col_28_ts, col_29_ts, col_30_ts,
  col_31_vc, col_32_vc, col_33_vc, col_34_vc, col_35_vc,
  col_36_int, col_37_int, col_38_int, col_39_int, col_40_int,
  col_41_num, col_42_num, col_43_num, col_44_num, col_45_num,
  col_46_text, col_47_text, col_48_text, col_49_text, col_50_text
)
SELECT
    gs                     AS col_01_int,
    gs * 2                 AS col_02_int,
    gs * 3                 AS col_03_int,
    gs * 4                 AS col_04_int,
    gs * 5                 AS col_05_int,
    gs * 1.11              AS col_06_num,
    gs * 2.22              AS col_07_num,
    gs * 3.33              AS col_08_num,
    gs * 4.44              AS col_09_num,
    gs * 5.55              AS col_10_num,
    'text_' || gs          AS col_11_text,
    'text2_' || gs         AS col_12_text,
    'text3_' || gs         AS col_13_text,
    'text4_' || gs         AS col_14_text,
    'text5_' || gs         AS col_15_text,
    (gs % 2 = 0)           AS col_16_bool,
    (gs % 3 = 0)           AS col_17_bool,
    (gs % 4 = 0)           AS col_18_bool,
    (gs % 5 = 0)           AS col_19_bool,
    (gs % 6 = 0)           AS col_20_bool,
    DATE '2020-01-01' + gs AS col_21_date,
    DATE '2020-01-01' + gs AS col_22_date,
    DATE '2020-01-01' + gs AS col_23_date,
    DATE '2020-01-01' + gs AS col_24_date,
    DATE '2020-01-01' + gs AS col_25_date,
    TIMESTAMP '2020-01-01 00:00:00' + (gs || ' hours')::interval AS col_26_ts,
    TIMESTAMP '2020-01-01 00:00:00' + (gs || ' hours')::interval AS col_27_ts,
    TIMESTAMP '2020-01-01 00:00:00' + (gs || ' hours')::interval AS col_28_ts,
    TIMESTAMP '2020-01-01 00:00:00' + (gs || ' hours')::interval AS col_29_ts,
    TIMESTAMP '2020-01-01 00:00:00' + (gs || ' hours')::interval AS col_30_ts,
    'vc_' || gs            AS col_31_vc,
    'vc2_' || gs           AS col_32_vc,
    'vc3_' || gs           AS col_33_vc,
    'vc4_' || gs           AS col_34_vc,
    'vc5_' || gs           AS col_35_vc,
    gs * 10                AS col_36_int,
    gs * 20                AS col_37_int,
    gs * 30                AS col_38_int,
    gs * 40                AS col_39_int,
    gs * 50                AS col_40_int,
    gs * 1.01              AS col_41_num,
    gs * 1.02              AS col_42_num,
    gs * 1.03              AS col_43_num,
    gs * 1.04              AS col_44_num,
    gs * 1.05              AS col_45_num,
    'extra_' || gs         AS col_46_text,
    'extra2_' || gs        AS col_47_text,
    'extra3_' || gs        AS col_48_text,
    'extra4_' || gs        AS col_49_text,
    'extra5_' || gs        AS col_50_text
FROM generate_series(1, 1000) AS gs;
